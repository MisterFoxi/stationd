use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::{collections::HashSet, path::Path};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Config {
    location: String,
    hostname: String,
    admin_email: String,
    port: u16,
    max_clients: u32,
    admin_user: String,
    admin_password_file: String,
    mounts: Vec<Mount>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Mount {
    name: String,
    password_file: String,
}

fn secret(dir: &Path, name: &str) -> Result<String> {
    // Only names, never paths outside the designated secrets directory.
    if name.is_empty()
        || !name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"-_".contains(&b))
    {
        bail!("invalid secret file name");
    }
    let value = std::fs::read_to_string(dir.join(name))
        .with_context(|| format!("cannot read secret file {name}"))?;
    let value = value.trim_end_matches(['\r', '\n']);
    if value.is_empty() || value.chars().any(char::is_control) {
        bail!("secret file {name} is empty or contains control characters");
    }
    Ok(value.to_owned())
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn render(config: &str, secrets: &Path) -> Result<String> {
    // Do not include toml's diagnostic: it may quote an accidentally inline secret.
    let c: Config = toml::from_str(config)
        .map_err(|_| anyhow::anyhow!("invalid Icecast TOML (schema or syntax)"))?;
    if c.port == 0 || c.max_clients == 0 || c.mounts.is_empty() || c.mounts.len() > 64 {
        bail!("port, max_clients and mounts must be nonzero (at most 64 mounts)");
    }
    for value in [&c.location, &c.hostname, &c.admin_email, &c.admin_user] {
        if value.trim().is_empty() || value.chars().any(char::is_control) {
            bail!("server identity fields must be nonempty and contain no control characters");
        }
    }
    let mut seen = HashSet::new();
    for mount in &c.mounts {
        if !mount.name.starts_with('/')
            || mount.name.len() < 2
            || mount.name.starts_with("/admin")
            || mount.name.contains("..")
            || mount
                .name
                .chars()
                .any(|c| c.is_whitespace() || c.is_control() || "?#\\".contains(c))
            || !seen.insert(&mount.name)
        {
            bail!("invalid or duplicate mount name");
        }
    }
    let admin = secret(secrets, &c.admin_password_file)?;
    let mut out = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by station-icecast-config. Contains secrets: runtime only. -->
<icecast>
  <location>{}</location>
  <admin>{}</admin>
  <hostname>{}</hostname>
  <limits>
    <clients>{}</clients>
    <sources>{}</sources>
    <queue-size>524288</queue-size>
    <client-timeout>30</client-timeout>
    <header-timeout>15</header-timeout>
    <source-timeout>10</source-timeout>
    <burst-size>8192</burst-size>
  </limits>
  <authentication>
    <admin-user>{}</admin-user>
    <admin-password>{}</admin-password>
  </authentication>
  <listen-socket><port>{}</port><bind-address>0.0.0.0</bind-address></listen-socket>
"#,
        xml(&c.location),
        xml(&c.admin_email),
        xml(&c.hostname),
        c.max_clients,
        c.mounts.len(),
        xml(&c.admin_user),
        xml(&admin),
        c.port
    );
    // No global source-password: only explicitly declared mounts accept sources.
    for mount in c.mounts {
        out.push_str(&format!(
            "  <mount type=\"normal\"><mount-name>{}</mount-name><password>{}</password><charset>UTF-8</charset></mount>\n",
            xml(&mount.name), xml(&secret(secrets, &mount.password_file)?)));
    }
    out.push_str(
        r#"  <paths>
    <basedir>/usr/share/icecast2</basedir>
    <logdir>/tmp</logdir>
    <webroot>/usr/share/icecast2/web</webroot>
    <adminroot>/usr/share/icecast2/admin</adminroot>
    <reportxmldb>/usr/share/icecast2/report-db.xml</reportxmldb>
    <alias source="/" destination="/status.xsl"/>
  </paths>
  <logging>
    <accesslog>-</accesslog>
    <errorlog>-</errorlog>
    <loglevel>information</loglevel>
  </logging>
  <security><chroot>false</chroot></security>
</icecast>
"#,
    );
    Ok(out)
}

fn run() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    if args.len() != 4 || args[0] != "render" {
        bail!("usage: station-icecast-config render <config.toml> <secrets-dir> <output.xml>");
    }
    let config = std::fs::read_to_string(&args[1]).context("cannot read Icecast TOML")?;
    let rendered = render(&config, Path::new(&args[2]))?;
    let output = Path::new(&args[3]);
    // Same-directory temporary file, exclusive creation, private from creation.
    let temporary = output.with_extension(format!("{}.tmp", std::process::id()));
    let result = (|| -> Result<()> {
        use std::io::Write;
        let mut opts = std::fs::OpenOptions::new();
        opts.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
        }
        let mut file = opts
            .open(&temporary)
            .context("cannot create private output")?;
        file.write_all(rendered.as_bytes())?;
        file.sync_all()?;
        std::fs::rename(&temporary, output).context("cannot replace output")?;
        Ok(())
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&temporary);
    }
    result
}

fn main() {
    if let Err(error) = run() {
        eprintln!("{error:#}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> (String, tempfile::TempDir) {
        let dir = tempfile::tempdir().unwrap();
        for name in ["admin-password", "source-a-password", "source-b-password"] {
            std::fs::write(dir.path().join(name), "test<&'\"\n").unwrap();
        }
        (
            include_str!("../../../config/icecast/icecast.toml").to_owned(),
            dir,
        )
    }

    #[test]
    fn escapes_secrets_and_declares_only_central_mounts() {
        let (config, dir) = fixture();
        let rendered = render(&config, dir.path()).unwrap();
        let doc = roxmltree::Document::parse(&rendered).unwrap();
        assert!(!doc.descendants().any(|n| n.has_tag_name("source-password")));
        let mounts: Vec<_> = doc
            .descendants()
            .filter(|n| n.has_tag_name("mount-name"))
            .map(|n| n.text().unwrap())
            .collect();
        assert_eq!(mounts, ["/test-a.mp3", "/test-b.mp3"]);
        let password = doc
            .descendants()
            .find(|n| n.has_tag_name("admin-password"))
            .unwrap();
        assert_eq!(password.text(), Some("test<&'\""));
    }

    #[test]
    fn rejects_unknown_fields_duplicate_mounts_paths_and_missing_secrets() {
        let (config, dir) = fixture();
        for invalid in [
            config.replace("port = 8000", "port = 0"),
            config.replace("port = 8000", "port = 8000\npassword = \"inline-secret\""),
            config.replace("/test-b.mp3", "/test-a.mp3"),
            config.replace("source-a-password", "../outside"),
            config.replace("source-a-password", "missing"),
            config.replace("/test-a.mp3", "/admin/stats"),
            config.replace("/test-a.mp3", "/bad mount"),
        ] {
            assert!(render(&invalid, dir.path()).is_err());
        }
    }

    #[test]
    fn refuses_empty_secret_without_disclosing_values() {
        let (config, dir) = fixture();
        std::fs::write(dir.path().join("admin-password"), "\n").unwrap();
        assert!(render(&config, dir.path()).is_err());
        let error = render(
            &config.replace("port = 8000", "port = \"sensitive-value\""),
            dir.path(),
        )
        .unwrap_err()
        .to_string();
        assert!(!error.contains("sensitive-value"));
    }
}
